#!/usr/bin/env python3
"""
Fill Form TX seven times from one definition and merge into a single print file.

Why an overlay rather than AcroForm values: merging seven copies of the same
form collides on field names — every copy would display the same title. So the
values are drawn as static text at the widget rectangles and flattened onto the
page. No form fields survive in the output, which means it prints identically in
any viewer, on any printer.

Blank form: pages 0-1 are instructions, pages 2-3 are the application. Only the
application pages are emitted: 7 x 2 = 14 pages. Print once, separate into
seven, sign seven times.

Deliberately left empty for pen: street address (3 places), telephone, signature
and date. Nothing about the claimant is invented.
"""

import io
import pathlib
from pypdf import PdfReader, PdfWriter
from reportlab.pdfgen import canvas
from reportlab.pdfbase.pdfmetrics import stringWidth

HERE = pathlib.Path(__file__).parent
BLANK = HERE / "formtx.pdf"
OUT = HERE / "FormTX_ALL_SEVEN_to_print.pdf"

FORM_PAGES = (2, 3)          # application pages inside the blank
FONT, SIZE, LEAD = "Helvetica", 8.5, 9.5

